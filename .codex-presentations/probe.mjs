import fs from 'node:fs/promises';
import { Presentation, PresentationFile } from '@oai/artifact-tool';
import { GlobalFonts } from '@napi-rs/canvas';
GlobalFonts.registerFromPath('C:/Windows/Fonts/msyh.ttc', 'Microsoft YaHei');
GlobalFonts.registerFromPath('C:/Windows/Fonts/msyhbd.ttc', 'Microsoft YaHei');
const p = Presentation.create({slideSize:{width:1280,height:720}});
p.theme.defaultFont = 'Microsoft YaHei';
const s = p.slides.add();
s.background.fill = '#ffffff';
const sh = s.shapes.add({geometry:'textbox', position:{left:72,top:72,width:1120,height:100},fill:'none',line:{fill:'none',width:0}});
sh.text = '面向多 Agent 的交互式绘图服务';
sh.text.style={fontSize:44,typeface:'Microsoft YaHei',color:'#222222',bold:true,insets:0};
s.speakerNotes.text='测试中文字体渲染';
await fs.writeFile(new URL('./probe.png',import.meta.url),new Uint8Array(await (await p.export({slide:s,format:'png',scale:1})).arrayBuffer()));
await (await PresentationFile.exportPptx(p)).save(new URL('./probe.pptx',import.meta.url).pathname.replace(/^\/(\w:)/,'$1'));
console.log('Probe succeeded');
